// Renders Opscode's system prompts into readable Markdown files (docs/prompts/), straight from the built code, so a change to
// any prompt shows up as a clean diff on GitHub. The prompts themselves stay in the source files named in each section:
// edit them there (never in docs/prompts), then run:
//   npm run build && npm run prompts:export        write docs/prompts/
//   node scripts/export-prompts.mjs --check        fail if docs/prompts/ is out of date (for CI / before a commit)
//
// Dynamic parts (the project name, the date, the person's notes) are replaced by obvious placeholders.

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "docs", "prompts");
const check = process.argv.includes("--check");
const load = (p) => import(join(root, "dist", p));
const fence = (t) => `\`\`\`text\n${String(t).replace(/\s+$/, "")}\n\`\`\``;
const files = new Map();
const HEAD = (title, source, note = "") => `# ${title}\n\n> Generated by \`npm run prompts:export\` from the code. **Do not edit this file**: edit the source below and re-run.\n>\n> Source: ${source}${note ? `\n>\n> ${note}` : ""}\n\n`;
const section = async (name, fn) => { try { files.set(name, await fn()); } catch (e) { files.set(name, `# ${name}\n\nCould not be rendered: ${e instanceof Error ? e.message : String(e)}\n`); } };

await section("voice-agent.md", async () => {
  const { voicePrompt } = await load("runtime/voiceagent/prompt.js");
  const { voiceTools } = await load("runtime/voiceagent/tools.js");
  const tools = voiceTools({ root: ".", workStart: () => "", workTell: async () => "", workStatus: () => "", workStop: () => "", workApprove: () => "" });
  return `${HEAD("The voice agent", "`src/runtime/voiceagent/prompt.ts` (prompt), `src/runtime/voiceagent/tools.ts` (its tools), `src/runtime/voiceagent/browser.ts` (its browser tools)", "The model you talk to in voice mode. It talks, searches the web in the Browser panel, writes briefs and starts workers.")}## System prompt (with the browser)\n\n${fence(voicePrompt({ project: "<project name>", today: "<today's date>", memory: "", browser: true }))}\n\n## Its own tools\n\n${tools.map((t) => `- **${t.def.name}**: ${t.def.description}`).join("\n")}\n`;
});

await section("manager.md", async () => {
  const { systemPrompt } = await load("runtime/chief/prompt.js");
  const { DEFAULT_SOUL, MODE_SOUL } = await load("runtime/chief/store.js");
  const profile = { id: "x", name: "<Manager's name>", brain: { engine: "claude-code" }, soul: "<the soul below>", autonomy: 2, updates: "milestones", worker_access: "edit", worker_engine: "claude-code", project_ids: [], max_parallel: 3, daily_chats: 20, ask_wait_minutes: 30, chat_id: "c", created_at: "", updated_at: "" };
  return `${HEAD("The Manager (Chief)", "`src/runtime/chief/prompt.ts`, `src/runtime/chief/store.ts` (the default souls)", "A Manager coordinates worker chats; it never does the work itself.")}## System prompt (autonomy 2, updates: milestones)\n\n${fence(systemPrompt(profile, [{ id: "p1", name: "<project>", path: "/path/to/project" }], "(automations the project has)", ""))}\n\n## Default soul (a plain Manager)\n\n${fence(DEFAULT_SOUL)}\n\n## Soul of a mode Conductor\n\n${fence(MODE_SOUL)}\n`;
});

await section("modes.md", async () => {
  const { MODES, modePrompt } = await load("runtime/chief/modes.js");
  const parts = Object.keys(MODES).map((id) => `## ${MODES[id].name ?? id}\n\n${fence(modePrompt(MODES[id]))}`);
  return `${HEAD("Modes: GODMODE, WARLORD, SHINOBI", "`src/runtime/chief/modes.ts` (`modePrompt`)", "The part of a Conductor's prompt that is generated from each mode's table (models, effort, review depth).")}${parts.join("\n\n")}\n`;
});

await section("workers.md", async () => {
  const { WORKER_RULES } = await load("runtime/chief/pack.js");
  const skills = await load("runtime/chief/skills.js");
  const kinds = skills.JOB_KINDS;
  const blocks = kinds.map((k) => `### ${k}\n\n${fence(skills.skillFor("build", k))}`);
  return `${HEAD("Workers: rules and job skills", "`src/runtime/chief/pack.ts` (rules), `src/runtime/chief/skills.ts` (skills per job kind)", "What a worker chat started by a Manager or Conductor is told.")}## Rules every worker gets\n\n${fence(Array.isArray(WORKER_RULES) ? WORKER_RULES.join("\n") : WORKER_RULES)}\n\n## Skill by job kind (role: build)\n\n${blocks.join("\n\n")}\n\n## Reviewer and checker\n\n### review\n\n${fence(skills.skillFor("review"))}\n\n### check\n\n${fence(skills.skillFor("check"))}\n`;
});

await section("agent.md", async () => {
  const { SYSTEM } = await load("runtime/agent/agent.js");
  return `${HEAD("The built-in agent (API models)", "`src/runtime/agent/agent.ts`", "Used when a chat runs on an API key. Claude Code, Codex, Antigravity and Qoder bring their own prompts.")}## System prompt\n\n${fence(SYSTEM("<project name>", "", [{ name: "<skill>", description: "<what it does>" }], undefined, false, []))}\n`;
});

await section("notes-and-skills.md", async () => {
  const claude = await load("runtime/engines/claude.js");
  const { CHECKPOINT_NOTE } = await load("runtime/checkpoint.js");
  const { SKILL_FINDER_NOTE } = await load("runtime/skillFinder.js");
  const { IMAGE_NOTE } = await load("runtime/imageNote.js");
  const { BUILTIN_SKILLS } = await load("runtime/builtinSkills.js");
  const notes = [["File links", "src/runtime/engines/claude.ts", claude.FILE_LINK_NOTE], ["Browser tools", "src/runtime/engines/claude.ts", claude.BROWSER_NOTE], ["iOS Simulator", "src/runtime/engines/claude.ts", claude.IOS_NOTE], ["Task checkpoints", "src/runtime/checkpoint.ts", CHECKPOINT_NOTE], ["Finding skills", "src/runtime/skillFinder.ts", SKILL_FINDER_NOTE], ["Image generation", "src/runtime/imageNote.ts", IMAGE_NOTE]];
  return `${HEAD("Notes given to every engine, and the built-in skills", "the files named in each section")}## Notes\n\n${notes.map(([t, s, v]) => `### ${t}\n\nSource: \`${s}\`\n\n${fence(v)}`).join("\n\n")}\n\n## Built-in skills (seeded into the state folder on start)\n\nSource: \`src/runtime/builtinSkills.ts\`\n\n${BUILTIN_SKILLS.map((s) => `### ${s.name}\n\n*${s.description}*\n\n${fence(s.body)}`).join("\n\n")}\n`;
});

const index = `# System prompts

Every system prompt Opscode sends to a model, in one place, as readable files. They are **generated from the code** (\`npm run prompts:export\`), so they are always the real text, and a change to a prompt shows up as a normal diff in a pull request or in GitHub Desktop.

**To change a prompt:** edit the source file named at the top of its page, run \`npm run build && npm run prompts:export\`, and commit both. \`node scripts/export-prompts.mjs --check\` fails when these pages are out of date.

| Page | What it is | Source |
|---|---|---|
| [voice-agent.md](voice-agent.md) | The model you talk to in voice mode, and its tools | \`src/runtime/voiceagent/\` |
| [manager.md](manager.md) | The Manager (Chief) and its souls | \`src/runtime/chief/prompt.ts\`, \`store.ts\` |
| [modes.md](modes.md) | GODMODE / WARLORD / SHINOBI | \`src/runtime/chief/modes.ts\` |
| [workers.md](workers.md) | Rules and skills for worker chats | \`src/runtime/chief/pack.ts\`, \`skills.ts\` |
| [agent.md](agent.md) | The built-in agent (API models) | \`src/runtime/agent/agent.ts\` |
| [notes-and-skills.md](notes-and-skills.md) | Notes given to every engine; built-in skills | several (see page) |

Also prompts, but built on the fly and not rendered here (they depend on the situation): the hand-off pack between engines (\`src/runtime/handoff.ts\`), automation step prompts (\`src/runtime/automations/runner.ts\`), sub-agent prompts (\`src/runtime/agent/agent.ts\`), and the Manager's hand-over text (\`src/runtime/chief/manager.ts\`). A written guide to prompt style: [../prompt-playbook.md](../prompt-playbook.md).
`;
files.set("README.md", index);

let bad = 0;
if (check) {
  for (const [name, text] of files) { const p = join(out, name); if (!existsSync(p) || readFileSync(p, "utf8") !== text) { console.error(`out of date: docs/prompts/${name}`); bad++; } }
  if (bad) { console.error("Run: npm run build && npm run prompts:export"); process.exit(1); }
  console.log(`docs/prompts is up to date (${files.size} files)`);
} else {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const [name, text] of files) writeFileSync(join(out, name), text);
  console.log(`wrote ${files.size} files to docs/prompts/`);
  for (const [name, text] of files) if (/Could not be rendered/.test(text)) console.warn(`  ! ${name}: ${text.split("\n")[2]}`);
}
